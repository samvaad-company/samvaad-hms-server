-- Medical records department (MRD): physical file tracking (locations, files, requests, movement trail),
-- document retention + folders, consent signatures sent to a patient's phone, discharge coding (ICD-10) with
-- deficiencies, and the birth / death registers. (MongoDB needs none of this.)

-- ── File tracking ────────────────────────────────────────────────────────────

create table if not exists mrd_locations (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  name        text not null,
  kind        text not null default 'MRD rack' check (kind in ('MRD rack','Archive room','Operation theatre','Nurse station','Doctor cabin','Other')),
  code        text not null default '',
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (hospital_id, name)
);

create table if not exists mrd_files (
  id               bigint generated by default as identity primary key,
  hospital_id      integer not null references hospitals(id),
  file_no          text not null,
  patient_id       bigint not null references patients(id),
  patient_name     text not null,
  patient_code     text not null default '',
  file_type        text not null default 'OPD' check (file_type in ('OPD','IPD')),
  status           text not null default 'Available' check (status in ('Available','Checked out','In transit','Archived')),
  location_id      bigint references mrd_locations(id) on delete set null,
  location_name    text not null default '',
  home_location_id bigint references mrd_locations(id) on delete set null,
  holder_name      text,
  due_on           text,
  checked_out_at   timestamptz,
  archived_on      text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  unique (hospital_id, file_no),
  unique (hospital_id, patient_id)          -- one file per patient
);
create index if not exists idx_mrd_files_status on mrd_files(hospital_id, status);
create index if not exists idx_mrd_files_location on mrd_files(location_id);

create table if not exists mrd_file_requests (
  id               bigint generated by default as identity primary key,
  hospital_id      integer not null references hospitals(id),
  file_id          bigint not null references mrd_files(id),
  file_no          text not null,
  patient_id       bigint not null,
  patient_name     text not null,
  urgency          text not null default 'Routine' check (urgency in ('Routine','Urgent')),
  status           text not null default 'Pending' check (status in ('Pending','Dispatched','Returned','Cancelled')),
  requested_on     text not null,
  requested_by     text not null default '',
  requested_for    text not null default '',
  destination_id   bigint references mrd_locations(id) on delete set null,
  destination_name text not null default '',
  note             text not null default '',
  dispatched_at    timestamptz,
  dispatched_by    text,
  returned_at      timestamptz,
  returned_by      text,
  cancelled_at     timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
-- A file can have only one open request at a time, whatever the application does.
create unique index if not exists uq_mrd_request_open_file on mrd_file_requests(file_id) where status in ('Pending','Dispatched');

create table if not exists mrd_file_movements (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  file_id       bigint not null references mrd_files(id),
  file_no       text not null,
  action        text not null check (action in ('Created','Checked out','Dispatched','Returned','Moved','Archived','Retrieved')),
  from_location text not null default '',
  to_location   text not null default '',
  holder_name   text,
  due_on        text,
  note          text not null default '',
  by_name       text not null default '',
  at            timestamptz not null default now(),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_mrd_movements_file on mrd_file_movements(file_id, at desc);

-- ── Documents: retention and folders ─────────────────────────────────────────

create table if not exists mrd_retention_policies (
  id              bigint generated by default as identity primary key,
  hospital_id     integer not null references hospitals(id),
  name            text not null,
  class           text not null check (class in ('Clinical','Financial','KYC','Statutory')),
  retention_years integer not null check (retention_years between 1 and 100),
  categories      jsonb not null default '[]'::jsonb,
  action_after    text not null default 'Review' check (action_after in ('Review','Destroy')),
  active          boolean not null default true,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create table if not exists mrd_folders (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  name        text not null,
  class       text not null default 'General' check (class in ('Clinical','Financial','KYC','Statutory','General')),
  description text not null default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (hospital_id, name)
);

alter table documents
  add column if not exists folder_id       bigint references mrd_folders(id) on delete set null,
  add column if not exists retention_state text,
  add column if not exists retain_until    text,
  add column if not exists retention_note  text,
  add column if not exists reviewed_by     text,
  add column if not exists reviewed_at     timestamptz;
create index if not exists idx_documents_folder on documents(folder_id);
create index if not exists idx_documents_retention on documents(hospital_id, retention_state);

-- ── Signatures ───────────────────────────────────────────────────────────────

create table if not exists signature_requests (
  id             bigint generated by default as identity primary key,
  hospital_id    integer not null references hospitals(id),
  patient_id     bigint references patients(id) on delete set null,
  patient_name   text not null,
  patient_code   text not null default '',
  patient_phone  text not null default '',
  form_title     text not null,
  form_body      text not null,
  language       text not null default 'English',
  token          text not null unique,
  status         text not null default 'Waiting' check (status in ('Waiting','Signed','Refused','Cancelled')),
  sent_by        text not null default '',
  sent_at        timestamptz not null default now(),
  expires_at     timestamptz not null,
  signed_at      timestamptz,
  signer_name    text,
  signature_data text,
  refused_reason text,
  cancelled_at   timestamptz,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists idx_signature_requests_hospital on signature_requests(hospital_id, status, sent_at desc);

-- ── Coding ───────────────────────────────────────────────────────────────────

create table if not exists mrd_coding_cases (
  id                bigint generated by default as identity primary key,
  hospital_id       integer not null references hospitals(id),
  admission_id      bigint not null,
  admission_no      text not null,
  patient_id        bigint references patients(id) on delete set null,
  patient_name      text not null,
  patient_code      text not null default '',
  doctor            text not null default '',
  admitted_on       text,
  status            text not null default 'Pending' check (status in ('Pending','In review','Deficient','Coded','Signed off')),
  principal_dx_code text not null default '',
  principal_dx_text text not null default '',
  secondary_dx      jsonb not null default '[]'::jsonb,
  procedures        jsonb not null default '[]'::jsonb,
  coder_name        text,
  coded_at          timestamptz,
  signed_off_by     text,
  signed_off_at     timestamptz,
  queued_at         timestamptz not null default now(),
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  unique (hospital_id, admission_id)        -- one coding case per admission
);
create index if not exists idx_mrd_coding_status on mrd_coding_cases(hospital_id, status);

create table if not exists mrd_deficiencies (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  case_id     bigint not null references mrd_coding_cases(id) on delete cascade,
  kind        text not null,
  note        text not null default '',
  status      text not null default 'Open' check (status in ('Open','Resolved')),
  raised_by   text not null default '',
  raised_at   timestamptz not null default now(),
  resolved_by text,
  resolved_at timestamptz,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists idx_mrd_deficiencies_case on mrd_deficiencies(case_id, status);

-- ── Registers (entries are permanent; a correction is a new entry that supersedes the old) ──

create table if not exists mrd_register_entries (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  register      text not null check (register in ('birth','death')),
  entry_no      text not null,
  entry_date    text not null,
  data          jsonb not null default '{}'::jsonb,
  report_to     text not null default '',
  filed_by      text not null default '',
  filed_at      timestamptz not null default now(),
  amends_id     bigint references mrd_register_entries(id),
  superseded_by bigint references mrd_register_entries(id),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (hospital_id, register, entry_no)
);

do $$
declare t text;
begin
  foreach t in array array['mrd_locations','mrd_files','mrd_file_requests','mrd_file_movements','mrd_retention_policies','mrd_folders','signature_requests','mrd_coding_cases','mrd_deficiencies','mrd_register_entries']
  loop
    execute format('drop trigger if exists trg_%1$s_updated on %1$s', t);
    execute format('create trigger trg_%1$s_updated before update on %1$s for each row execute function set_updated_at()', t);
  end loop;
end $$;
