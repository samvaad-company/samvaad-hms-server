-- Blood bank rebuilt around individual bags (units): collection, the five serology tests, component
-- processing, cross-matching with reservation, issue and transfusion, discards. Donors gain a donor number,
-- date of birth, deferral details, and an ID proof kept as TYPE + LAST 4 only (never the full number).
-- The old aggregate stock and issue tables are no longer used. (MongoDB needs none of this.)

alter table blood_donors
  add column if not exists donor_no        text not null default '',
  add column if not exists dob             text,
  add column if not exists id_proof_type   text not null default '',
  add column if not exists id_proof_last4  text not null default '',
  add column if not exists deferral_reason text not null default '',
  add column if not exists deferred_until  text;
-- Old rows may hold a full ID number; keep only its last four characters.
update blood_donors
   set id_proof_last4 = right(aadhaar_number, 4), id_proof_type = 'aadhaar'
 where coalesce(aadhaar_number, '') <> '' and id_proof_last4 = '';
update blood_donors set aadhaar_number = '' where coalesce(aadhaar_number, '') <> '';

create table if not exists blood_units (
  id             bigint generated by default as identity primary key,
  hospital_id    integer not null references hospitals(id),
  unit_no        text not null,
  source         text not null default 'Donation' check (source in ('Donation','Purchased')),
  donor_id       bigint references blood_donors(id) on delete set null,
  donor_no       text not null default '',
  supplier       text not null default '',
  bag_no         text not null default '',
  blood_group    text not null check (blood_group in ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  component      text not null check (component in ('Whole blood','PRBC','Platelets','Plasma','Cryoprecipitate')),
  volume_ml      numeric(8,2) not null,
  collected_on   text not null,
  expiry_on      text not null,
  serology       jsonb not null default '{"hiv":"","hbsag":"","hcv":"","malaria":"","syphilis":""}'::jsonb,
  serology_by    text,
  serology_on    text,
  status         text not null default 'Quarantined' check (status in ('Quarantined','Available','Cross-matched','Issued','Processed','Discarded')),
  root_unit_id   bigint,
  parent_unit_id bigint,
  left_on        text,
  discard_reason text not null default '',
  discarded_by   text,
  created_by     text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  unique (hospital_id, unit_no)
);
create index if not exists idx_blood_units_stock on blood_units(hospital_id, status, blood_group);
create index if not exists idx_blood_units_root on blood_units(root_unit_id);

create table if not exists blood_crossmatches (
  id             bigint generated by default as identity primary key,
  hospital_id    integer not null references hospitals(id),
  xm_no          text not null,
  patient_id     bigint references patients(id) on delete set null,
  patient_name   text not null,
  patient_code   text not null default '',
  unit_id        bigint not null references blood_units(id),
  unit_no        text not null,
  unit_group     text not null,
  unit_component text not null default '',
  requested_at   timestamptz not null default now(),
  requested_by   text not null default '',
  result         text not null default 'pending' check (result in ('pending','compatible','incompatible')),
  result_by      text,
  result_at      timestamptz,
  status         text not null default 'requested' check (status in ('requested','resulted','issued','cancelled')),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  unique (hospital_id, xm_no)
);
-- A unit can be held by only one open cross-match at a time, whatever the application does.
create unique index if not exists uq_blood_xm_open_unit on blood_crossmatches(unit_id) where status in ('requested','resulted');

create table if not exists blood_transfusions (
  id             bigint generated by default as identity primary key,
  hospital_id    integer not null references hospitals(id),
  issue_no       text not null,
  crossmatch_id  bigint not null references blood_crossmatches(id),
  patient_id     bigint references patients(id) on delete set null,
  patient_name   text not null,
  patient_code   text not null default '',
  unit_id        bigint not null references blood_units(id),
  unit_no        text not null,
  unit_group     text not null,
  unit_component text not null default '',
  issued_at      timestamptz not null default now(),
  issued_by      text not null default '',
  transfused_at  timestamptz,
  transfused_by  text,
  disposition    text not null default '',
  returned_at    timestamptz,
  reactions      jsonb not null default '[]'::jsonb,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  unique (hospital_id, issue_no)
);

do $$
declare t text;
begin
  foreach t in array array['blood_units','blood_crossmatches','blood_transfusions']
  loop
    execute format('drop trigger if exists trg_%1$s_updated on %1$s', t);
    execute format('create trigger trg_%1$s_updated before update on %1$s for each row execute function set_updated_at()', t);
  end loop;
end $$;
