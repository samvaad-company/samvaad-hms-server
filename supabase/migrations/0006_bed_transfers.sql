-- ============================================================================
-- Samvaad HMS — Bed transfer history
-- Logs every bed-to-bed patient move made from the beds board or IPD module.
-- ============================================================================

create table if not exists bed_transfers (
  id            bigint generated by default as identity primary key,
  patient_name  text not null default '',
  from_label    text not null default '',
  to_label      text not null default '',
  transfer_date text not null default '',
  reason        text not null default '',
  status        text not null default 'Completed' check (status in ('Completed','Pending')),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create trigger trg_bed_transfers_updated before update on bed_transfers
  for each row execute function set_updated_at();
