-- ============================================================================
-- Samvaad HMS — Service modules
-- Blood bank, radiology, ambulance, birth/death records, TPA, finance, and
-- general inventory. Also adds the IPD credit-limit column and widens the
-- bill type check to the new bill sources.
-- ============================================================================

-- ── ipd_admissions: credit limit ────────────────────────────────────────────
alter table ipd_admissions
  add column if not exists credit_limit numeric(12,2) not null default 0;

-- ── bills: new sources ───────────────────────────────────────────────────────
alter table bills drop constraint if exists bills_type_check;
alter table bills add constraint bills_type_check
  check (type in ('OPD','Pharmacy','Lab','IPD','Blood','Ambulance','Radiology'));

-- ── blood_donors ─────────────────────────────────────────────────────────────
create table if not exists blood_donors (
  id                 bigint generated by default as identity primary key,
  name               text not null,
  age                integer not null check (age between 18 and 65),
  gender             text not null check (gender in ('Male','Female')),
  blood_group        text not null check (blood_group in ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  phone              text not null default '',
  last_donation_date text not null default '',
  total_donations    integer not null default 0 check (total_donations >= 0),
  status             text not null default 'Eligible' check (status in ('Eligible','Deferred')),
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create index if not exists idx_blood_donors_group on blood_donors(blood_group);
create trigger trg_blood_donors_updated before update on blood_donors
  for each row execute function set_updated_at();

-- ── blood_stock ──────────────────────────────────────────────────────────────
create table if not exists blood_stock (
  id           bigint generated by default as identity primary key,
  blood_group  text not null check (blood_group in ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  component    text not null check (component in ('Whole Blood','Plasma','Platelets','RBC')),
  units        integer not null default 0 check (units >= 0),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (blood_group, component)
);
create trigger trg_blood_stock_updated before update on blood_stock
  for each row execute function set_updated_at();

-- ── blood_issues ─────────────────────────────────────────────────────────────
create table if not exists blood_issues (
  id           bigint generated by default as identity primary key,
  patient_id   bigint references patients(id) on delete set null,
  patient_name text not null,
  blood_group  text not null check (blood_group in ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  component    text not null check (component in ('Whole Blood','Plasma','Platelets','RBC')),
  units        integer not null check (units > 0),
