-- ============================================================================
-- Samvaad HMS: patient loyalty programme.
--   * appointments gain optional "referred by" and "family of" links to other patients.
--   * loyalty_adjustments: points an administrator added or took off a patient by hand.
-- The programme's cards, prices, colours and scoring rules live in setup_records (kind 'config:loyalty').
-- ============================================================================

alter table appointments
  add column if not exists referred_by_patient_id bigint references patients(id) on delete set null,
  add column if not exists referred_by_name       text,
  add column if not exists family_of_patient_id   bigint references patients(id) on delete set null,
  add column if not exists family_of_name         text,
  add column if not exists family_relation        text;

create index if not exists idx_appointments_referred_by on appointments(referred_by_patient_id);
create index if not exists idx_appointments_family_of on appointments(family_of_patient_id);

create table if not exists loyalty_adjustments (
  id           bigint generated by default as identity primary key,
  hospital_id  bigint not null references hospitals(id) on delete cascade,
  patient_id   bigint not null references patients(id) on delete cascade,
  points       integer not null,
  reason       text not null default '',
  by_user_id   bigint,
  by_name      text not null default '',
  created_at   timestamptz not null default now()
);
create index if not exists idx_loyalty_adjustments_patient on loyalty_adjustments(patient_id);
create index if not exists idx_loyalty_adjustments_hospital on loyalty_adjustments(hospital_id);

alter table loyalty_adjustments enable row level security;
