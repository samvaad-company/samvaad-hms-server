-- Operation theatre: rooms, equipment, and a fuller surgery booking (case type, category, duration,
-- surgical team, equipment, anaesthetic fitness, actual start / end). (MongoDB needs none of this.)

create table if not exists ot_rooms (
  id           bigint generated by default as identity primary key,
  hospital_id  integer not null references hospitals(id),
  name         text not null,
  kind         text not null default 'Major' check (kind in ('Major','Minor','Daycare')),
  active       boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (hospital_id, name)
);

create table if not exists ot_equipment (
  id           bigint generated by default as identity primary key,
  hospital_id  integer not null references hospitals(id),
  name         text not null,
  status       text not null default 'Available' check (status in ('Available','Maintenance')),
  note         text not null default '',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

alter table ot_schedules
  add column if not exists booking_no            text not null default '',
  add column if not exists case_type             text not null default 'Elective',
  add column if not exists surgery_name          text not null default '',
  add column if not exists category              text not null default 'Major',
  add column if not exists procedure_code        text not null default '',
  add column if not exists duration_min          integer not null default 60,
  add column if not exists room_id               bigint references ot_rooms(id) on delete set null,
  add column if not exists co_surgeon_id         bigint references doctors(id) on delete set null,
  add column if not exists co_surgeon            text not null default '',
  add column if not exists anesthetist_id        bigint references doctors(id) on delete set null,
  add column if not exists anaesthesia_type      text not null default '',
  add column if not exists scrub_nurse_id        bigint references staff(id) on delete set null,
  add column if not exists scrub_nurse           text not null default '',
  add column if not exists circulating_nurse_id  bigint references staff(id) on delete set null,
  add column if not exists circulating_nurse     text not null default '',
  add column if not exists technician_ids        jsonb not null default '[]'::jsonb,
  add column if not exists technicians           jsonb not null default '[]'::jsonb,
  add column if not exists equipment_ids         jsonb not null default '[]'::jsonb,
  add column if not exists equipment             jsonb not null default '[]'::jsonb,
  add column if not exists special_requirements  text not null default '',
  add column if not exists allow_overlap         boolean not null default false,
  add column if not exists fitness               text not null default 'Pending',
  add column if not exists started_at            timestamptz,
  add column if not exists ended_at              timestamptz;

alter table ot_schedules drop constraint if exists ot_schedules_case_type_check;
alter table ot_schedules add constraint ot_schedules_case_type_check check (case_type in ('Elective','Emergency','Outdoor'));
alter table ot_schedules drop constraint if exists ot_schedules_category_check;
alter table ot_schedules add constraint ot_schedules_category_check check (category in ('Major','Minor','Daycare'));
alter table ot_schedules drop constraint if exists ot_schedules_fitness_check;
alter table ot_schedules add constraint ot_schedules_fitness_check check (fitness in ('Pending','Fit','Unfit'));

create index if not exists idx_ot_schedules_day on ot_schedules(hospital_id, scheduled_date);

