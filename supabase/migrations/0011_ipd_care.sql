-- ============================================================================
-- Samvaad HMS — Inpatient care records
-- Daily notes, doctor rounds, diet chart and the medication chart were all
-- rendered from hardcoded arrays with no way to add or update anything.
-- ============================================================================

create table if not exists ipd_notes (
  id           bigint generated by default as identity primary key,
  admission_id bigint not null references ipd_admissions(id) on delete cascade,
  note_type    text not null default 'Daily Note'
               check (note_type in ('Daily Note','Doctor Round','Diet')),
  note_date    text not null default '',
  note_time    text not null default '',
  author       text not null default '',
  content      text not null,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists idx_ipd_notes_admission on ipd_notes(admission_id, note_type);
create trigger trg_ipd_notes_updated before update on ipd_notes
  for each row execute function set_updated_at();

create table if not exists ipd_medications (
  id            bigint generated by default as identity primary key,
  admission_id  bigint not null references ipd_admissions(id) on delete cascade,
  medicine_name text not null,
  dosage        text not null default '',
  frequency     text not null default '',
  route         text not null default 'Oral',
  start_date    text not null default '',
  end_date      text not null default '',
  status        text not null default 'Active'
                check (status in ('Active','Stopped','Completed')),
  last_given_at text not null default '',
  notes         text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_ipd_meds_admission on ipd_medications(admission_id, status);
create trigger trg_ipd_meds_updated before update on ipd_medications
  for each row execute function set_updated_at();

alter table ipd_notes       enable row level security;
alter table ipd_medications enable row level security;
