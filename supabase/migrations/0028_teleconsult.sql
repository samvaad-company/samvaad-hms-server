-- ============================================================================
-- Samvaad HMS — paid video consultations (tele-consult)
-- The hospital's admin sets the fee; patients book from the patient portal,
-- pay online, and the confirmed booking becomes a 'Tele-consult' appointment
-- carrying a Google Meet link. (MongoDB needs none of this — it's schemaless.)
-- ============================================================================

alter table hospitals
  add column if not exists teleconsult_enabled boolean not null default false,
  add column if not exists teleconsult_price   numeric(10,2) check (teleconsult_price >= 0),
  add column if not exists teleconsult_meet_access text not null default 'OPEN'
    check (teleconsult_meet_access in ('OPEN','TRUSTED','RESTRICTED'));

alter table appointments drop constraint if exists appointments_type_check;
alter table appointments
  add constraint appointments_type_check check (type in ('Walk-in','Booked','Tele-consult'));
alter table appointments
  add column if not exists video_url      text,
  add column if not exists video_provider text,
  add column if not exists meet_error     text,
  add column if not exists meet_access    text,
  add column if not exists meet_warning   text,
  add column if not exists meet_event_id  text,
  add column if not exists slot_minutes   integer,
  add column if not exists reschedule_count integer not null default 0,
  add column if not exists rescheduled_from text,
  add column if not exists consult_amount numeric(10,2),
  add column if not exists payment_status text,
  add column if not exists booking_id     bigint,
  add column if not exists payment_id     text,
  add column if not exists order_id       text;
create index if not exists idx_appointments_type on appointments(type);
-- One appointment per booking, enforced by the database so a webhook and the patient's own
-- confirmation arriving together can never double-book.
create unique index if not exists uniq_appointments_booking on appointments(booking_id) where booking_id is not null;

create table if not exists teleconsult_bookings (
  id                 bigint generated by default as identity primary key,
  hospital_id        bigint not null references hospitals(id) on delete cascade,
  patient_id         bigint not null references patients(id) on delete cascade,
  patient_name       text not null,
  patient_email      text,
  doctor_id          bigint not null references doctors(id) on delete cascade,
  doctor_name        text not null,
  appointment_date   text not null,
  appointment_time   text not null,
  reason             text not null default '',
  amount             numeric(10,2) not null default 0,
  currency           text not null default 'INR',
  source             text not null default 'portal' check (source in ('portal','link','staff')),
  status             text not null default 'pending_payment'
    check (status in ('pending_payment','confirmed','failed','slot_conflict','cancelled','expired')),
  payment_mode       text not null default '',
  gateway_order_id   text,
  gateway_payment_id text,
  paid_at            timestamptz,
  appointment_id     bigint references appointments(id) on delete set null,
  failure_reason     text,
  created_by         bigint references users(id) on delete set null,
  refund_reference   text,
  refunded_at        timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create index if not exists idx_tc_bookings_hospital on teleconsult_bookings(hospital_id);
create index if not exists idx_tc_bookings_patient on teleconsult_bookings(patient_id);
create index if not exists idx_tc_bookings_order on teleconsult_bookings(gateway_order_id);
create trigger trg_tc_bookings_updated before update on teleconsult_bookings
  for each row execute function set_updated_at();

create table if not exists google_connections (
  id                bigint generated by default as identity primary key,
  hospital_id       bigint not null unique references hospitals(id) on delete cascade,
  account_email     text not null default '',
  refresh_token_enc text not null,
  connected_by      bigint references users(id) on delete set null,
  scopes            text not null default '',
  needs_reconnect   boolean not null default false,
  last_error        text,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
create trigger trg_google_connections_updated before update on google_connections
  for each row execute function set_updated_at();

-- The payment ledger: one row per gateway payment (or staff receipt), tying the payment id and order id
-- to the booking, appointment, patient and doctor.
create table if not exists teleconsult_payments (
  id                 bigint generated by default as identity primary key,
  hospital_id        bigint not null references hospitals(id) on delete cascade,
  booking_id         bigint not null references teleconsult_bookings(id) on delete cascade,
  appointment_id     bigint references appointments(id) on delete set null,
  patient_id         bigint not null references patients(id) on delete cascade,
  patient_name       text not null,
  doctor_id          bigint not null references doctors(id) on delete cascade,
  doctor_name        text not null,
  order_id           text,
  payment_id         text,
  amount             numeric(10,2) not null default 0,
  currency           text not null default 'INR',
  mode               text not null default '',
  method             text,
  status             text not null default 'created'
    check (status in ('created','authorized','captured','failed','refunded')),
  signature_verified boolean not null default false,
  recorded_via       text not null default 'system',
  error_code         text,
  error_description  text,
  note               text,
  gateway_email      text,
  gateway_contact    text,
  refund_id          text,
  refunded_at        timestamptz,
  events             jsonb not null default '[]'::jsonb,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create unique index if not exists uniq_tc_payments_payment on teleconsult_payments(payment_id) where payment_id is not null;
create index if not exists idx_tc_payments_booking on teleconsult_payments(booking_id);
create index if not exists idx_tc_payments_order on teleconsult_payments(order_id);
create index if not exists idx_tc_payments_hospital on teleconsult_payments(hospital_id);
create trigger trg_tc_payments_updated before update on teleconsult_payments
  for each row execute function set_updated_at();

-- Doctor scheduling: patients per hour (must divide 60 so every patient gets whole minutes), and whether the doctor
-- takes video consultations with the weekly hours reserved for them: [{"day":"Monday","start":"16:00","end":"18:00"}].
alter table doctors
  add column if not exists patients_per_hour integer not null default 2
    check (patients_per_hour in (1,2,3,4,5,6,10,12,15,20,30,60)),
  add column if not exists video_enabled     boolean not null default false,
  add column if not exists video_hours       jsonb   not null default '[]'::jsonb;
