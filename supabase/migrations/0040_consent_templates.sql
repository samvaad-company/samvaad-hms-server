-- Consent templates a hospital writes itself (the built-in forms live in code), and a snapshot of a consent's wording
-- taken when it is made, so later edits to a template never change a consent that has already been issued.

create table if not exists consent_templates (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  key         text not null,
  titles      jsonb not null default '{}'::jsonb,
  bodies      jsonb not null default '{}'::jsonb,
  active      boolean not null default true,
  created_by  text not null default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (hospital_id, key)
);
drop trigger if exists trg_consent_templates_updated on consent_templates;
create trigger trg_consent_templates_updated before update on consent_templates for each row execute function set_updated_at();

alter table signature_requests add column if not exists template_texts jsonb;
