-- ============================================================================
-- Samvaad HMS — Pharmacy purchase orders and counter sales
-- Both screens were UI mockups with no persistence. Receiving a PO increases
-- stock; a sale decreases it and raises a Pharmacy bill.
-- ============================================================================

create table if not exists purchase_orders (
  id            bigint generated by default as identity primary key,
  po_number     text not null unique,
  supplier      text not null,
  order_date    text not null default '',
  expected_date text not null default '',
  item_count    integer not null default 0,
  total         numeric(12,2) not null default 0,
  status        text not null default 'Pending' check (status in ('Pending','Received','Cancelled')),
  notes         text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_po_status on purchase_orders(status);
create trigger trg_purchase_orders_updated before update on purchase_orders
  for each row execute function set_updated_at();

create table if not exists purchase_order_items (
  id                bigint generated by default as identity primary key,
  purchase_order_id bigint not null references purchase_orders(id) on delete cascade,
  pharmacy_item_id  bigint references pharmacy_items(id) on delete set null,
  medicine_name     text not null,
  quantity          integer not null check (quantity > 0),
  unit_cost         numeric(12,2) not null default 0,
  created_at        timestamptz not null default now()
);
create index if not exists idx_po_items_po on purchase_order_items(purchase_order_id);

create table if not exists pharmacy_sales (
  id              bigint generated by default as identity primary key,
  sale_number     text not null unique,
  patient_id      bigint references patients(id) on delete set null,
  patient_name    text not null default 'Walk-in',
  prescription_id bigint references prescriptions(id) on delete set null,
  rx_number       text not null default '',
  item_count      integer not null default 0,
  subtotal        numeric(12,2) not null default 0,
  discount        numeric(12,2) not null default 0,
  total           numeric(12,2) not null default 0,
  payment_mode    text not null default 'Cash' check (payment_mode in ('Cash','UPI','Card','Cheque','Insurance')),
  sale_date       text not null default '',
  bill_id         bigint references bills(id) on delete set null,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists idx_sales_patient on pharmacy_sales(patient_id);
create trigger trg_pharmacy_sales_updated before update on pharmacy_sales
  for each row execute function set_updated_at();

create table if not exists pharmacy_sale_items (
  id               bigint generated by default as identity primary key,
  sale_id          bigint not null references pharmacy_sales(id) on delete cascade,
  pharmacy_item_id bigint references pharmacy_items(id) on delete set null,
  medicine_name    text not null,
  quantity         integer not null check (quantity > 0),
  unit_price       numeric(12,2) not null default 0,
  line_total       numeric(12,2) not null default 0,
  created_at       timestamptz not null default now()
);
create index if not exists idx_sale_items_sale on pharmacy_sale_items(sale_id);

alter table purchase_orders      enable row level security;
alter table purchase_order_items enable row level security;
alter table pharmacy_sales       enable row level security;
alter table pharmacy_sale_items  enable row level security;
