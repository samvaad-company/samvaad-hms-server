-- Pharmacy purchasing: cash / credit purchase bills, who makes and who supplies each medicine, HSN and Schedule H1, and the
-- supplier credit ledger (stock returned to a supplier earns credit that the next bill for the same supplier and manufacturer uses).
-- (MongoDB needs none of this.)

alter table pharmacy_items add column if not exists manufacturer text;
alter table pharmacy_items add column if not exists manufacturer_id bigint;
alter table pharmacy_items add column if not exists supplier_id bigint;
alter table pharmacy_items add column if not exists hsn text;
alter table pharmacy_items add column if not exists is_h1 boolean not null default false;

alter table purchase_orders add column if not exists supplier_id bigint;
alter table purchase_orders add column if not exists payment_type text not null default 'Cash' check (payment_type in ('Cash','Credit'));
alter table purchase_orders add column if not exists payment_status text not null default 'Paid' check (payment_status in ('Paid','Unpaid'));
alter table purchase_orders add column if not exists credit_applied numeric(12,2) not null default 0 check (credit_applied >= 0);
alter table purchase_orders add column if not exists net_payable numeric(12,2);

alter table purchase_order_items add column if not exists manufacturer text;
alter table purchase_order_items add column if not exists manufacturer_id bigint;
alter table purchase_order_items add column if not exists hsn text;
alter table purchase_order_items add column if not exists is_h1 boolean not null default false;

create table if not exists supplier_credits (
  id               bigint generated by default as identity primary key,
  hospital_id      integer not null references hospitals(id),
  supplier         text not null,
  supplier_id      bigint,
  manufacturer     text not null default '',
  manufacturer_id  bigint,
  entry_type       text not null check (entry_type in ('Return','Applied','Reversal','Adjustment')),
  amount           numeric(12,2) not null,
  reference        text not null default '',
  purchase_order_id bigint references purchase_orders(id) on delete set null,
  pharmacy_item_id bigint references pharmacy_items(id) on delete set null,
  medicine_name    text,
  quantity         integer,
  unit_cost        numeric(12,2),
  reason           text,
  created_by       text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists idx_supplier_credits_pair on supplier_credits(hospital_id, supplier, manufacturer);
create index if not exists idx_supplier_credits_po on supplier_credits(purchase_order_id);
