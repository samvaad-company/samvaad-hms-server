-- Pharmacy dispensing: a price per medicine, stock held per batch, the dispenses themselves (with their billing choice) and returns.
-- (MongoDB needs none of this.)

alter table pharmacy_items add column if not exists unit_price numeric(12,2);

create table if not exists pharmacy_batches (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  item_id     bigint not null references pharmacy_items(id) on delete cascade,
  batch_no    text not null,
  expiry_date text not null default '',
  quantity    integer not null default 0 check (quantity >= 0),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists idx_pharmacy_batches_item on pharmacy_batches(hospital_id, item_id);

create table if not exists pharmacy_dispenses (
  id              bigint generated by default as identity primary key,
  hospital_id     integer not null references hospitals(id),
  dispense_no     text not null,
  patient_id      bigint references patients(id) on delete set null,
  patient_name    text not null,
  walk_in_note    text not null default '',
  prescription_id bigint references prescriptions(id) on delete set null,
  rx_number       text not null default '',
  billing         text not null default 'none' check (billing in ('none','separate','patient')),
  bill_id         bigint references bills(id) on delete set null,
  bill_number     text,
  admission_id    bigint,
  admission_no    text,
  subtotal        numeric(12,2) not null default 0 check (subtotal >= 0),
  status          text not null default 'Dispensed' check (status in ('Dispensed','Part returned','Returned')),
  dispensed_by    text not null default '',
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (hospital_id, dispense_no)
);
create index if not exists idx_pharmacy_dispenses_patient on pharmacy_dispenses(hospital_id, patient_id);

create table if not exists pharmacy_dispense_lines (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  dispense_id   bigint not null references pharmacy_dispenses(id) on delete cascade,
  item_id       bigint not null references pharmacy_items(id),
  medicine_name text not null,
  batch_id      bigint references pharmacy_batches(id) on delete set null,
  batch_no      text not null default '',
  expiry_date   text not null default '',
  quantity      integer not null check (quantity > 0),
  returned_qty  integer not null default 0 check (returned_qty >= 0),
  unit_price    numeric(12,2) not null default 0 check (unit_price >= 0),
  line_total    numeric(12,2) not null default 0 check (line_total >= 0),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  -- A line can never be returned beyond what went out, whatever the application does.
  check (returned_qty <= quantity)
);
create index if not exists idx_pharmacy_dispense_lines_dispense on pharmacy_dispense_lines(dispense_id);

create table if not exists pharmacy_returns (
  id             bigint generated by default as identity primary key,
  hospital_id    integer not null references hospitals(id),
  dispense_id    bigint not null references pharmacy_dispenses(id) on delete cascade,
  line_id        bigint not null references pharmacy_dispense_lines(id) on delete cascade,
  medicine_name  text not null,
  batch_no       text not null default '',
  quantity       integer not null check (quantity > 0),
  condition      text not null check (condition in ('Usable','Damaged','Expired')),
  credit_note_no text not null default '',
  credit_value   numeric(12,2) not null default 0 check (credit_value >= 0),
  reason         text not null default '',
  returned_by    text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists idx_pharmacy_returns_dispense on pharmacy_returns(dispense_id);
