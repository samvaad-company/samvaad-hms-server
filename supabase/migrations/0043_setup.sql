-- Setup: department details used by Masters, and one generic table behind every Setup master (services, rate plans,
-- payers, registration lists, facility, branches…) and the hospital's configuration blobs. (MongoDB needs none of this.)

alter table departments
  add column if not exists code      text,
  add column if not exists specialty text,
  add column if not exists clinical  boolean not null default true,
  add column if not exists active    boolean not null default true;

create table if not exists setup_records (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  kind        text not null,
  code        text not null default '',
  name        text not null,
  active      boolean not null default true,
  sort_order  integer not null default 0,
  data        jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists idx_setup_records_kind on setup_records(hospital_id, kind);
-- A code identifies one entry within its master, whatever the application does.
create unique index if not exists uq_setup_records_code on setup_records(hospital_id, kind, upper(code)) where code <> '';
-- A hospital has one of each configuration blob.
create unique index if not exists uq_setup_records_config on setup_records(hospital_id, kind) where kind like 'config:%';
