-- ============================================================================
-- Samvaad HMS: cashless pre-authorisation forms.
--   * preauth_forms: one request per patient on an insurer's form; its details are JSON under standard field keys.
--     Status runs Draft -> Awaiting doctor -> Awaiting stamp -> Ready. The signature and stamp images are copied onto the form
--     when it is signed and stamped, so it stays as signed.
--   * signature_assets: a doctor's signature and stamp, and the hospital's stamp (owner_id 0).
--   * notifications: what each person sees under the bell, one row per recipient.
-- ============================================================================

create table if not exists preauth_forms (
  id                    bigint generated by default as identity primary key,
  hospital_id           bigint not null references hospitals(id) on delete cascade,
  form_key              text not null,
  form_name             text not null default '',
  patient_id            bigint references patients(id) on delete set null,
  patient_name          text not null default '',
  admission_id          bigint,
  doctor_id             bigint,
  doctor_name           text not null default '',
  status                text not null default 'Draft' check (status in ('Draft', 'Awaiting doctor', 'Awaiting stamp', 'Ready')),
  "values"              jsonb not null default '{}'::jsonb,
  created_by_id         bigint,
  created_by            text not null default '',
  doctor_signed_at      timestamptz,
  doctor_signed_by      text,
  doctor_signature_img  text,
  doctor_stamp_img      text,
  stamped_at            timestamptz,
  stamped_by            text,
  hospital_stamp_img    text,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);
create index if not exists idx_preauth_forms_hospital on preauth_forms(hospital_id, status);
create index if not exists idx_preauth_forms_patient on preauth_forms(patient_id);
create index if not exists idx_preauth_forms_doctor on preauth_forms(doctor_id);

create table if not exists signature_assets (
  id           bigint generated by default as identity primary key,
  hospital_id  bigint not null references hospitals(id) on delete cascade,
  kind         text not null check (kind in ('doctor_signature', 'doctor_stamp', 'hospital_stamp')),
  owner_id     bigint not null default 0,
  image        text not null,
  updated_by   text not null default '',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (hospital_id, kind, owner_id)
);

create table if not exists notifications (
  id           bigint generated by default as identity primary key,
  hospital_id  bigint not null references hospitals(id) on delete cascade,
  user_id      bigint not null,
  kind         text not null default '',
  title        text not null,
  body         text not null default '',
  link         text not null default '',
  read_at      timestamptz,
  created_at   timestamptz not null default now()
);
create index if not exists idx_notifications_user on notifications(user_id, read_at);

alter table preauth_forms enable row level security;
alter table signature_assets enable row level security;
alter table notifications enable row level security;
