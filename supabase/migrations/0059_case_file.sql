-- ============================================================================
-- Samvaad HMS: the IPD case file, the set of forms kept with an admitted patient.
--   * case_file_entries: one row per form per admission (progress note, treatment sheet, TPR chart, ...). The form's content is JSON;
--     `version` goes up on every save so two people editing at once are told rather than overwritten.
-- ============================================================================

create table if not exists case_file_entries (
  id            bigint generated by default as identity primary key,
  hospital_id   bigint not null references hospitals(id) on delete cascade,
  admission_id  bigint not null references ipd_admissions(id) on delete cascade,
  form_key      text not null,
  data          jsonb not null default '{}'::jsonb,
  version       integer not null default 1,
  updated_by    text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (admission_id, form_key)
);

create index if not exists idx_case_file_entries_admission on case_file_entries(hospital_id, admission_id);
