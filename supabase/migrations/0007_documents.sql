-- ============================================================================
-- Samvaad HMS — Document attachments
-- File metadata for patient documents, lab reports, donor ID proofs, etc.
-- Binary contents live in the configured storage driver, not in Postgres.
-- ============================================================================

create table if not exists documents (
  id           bigint generated by default as identity primary key,
  owner_type   text not null check (owner_type in ('patient','lab','radiology','donor','staff')),
  owner_id     bigint not null,
  category     text not null default 'General',
  file_name    text not null,
  mime_type    text not null,
  size_bytes   bigint not null check (size_bytes >= 0),
  storage_key  text not null,
  uploaded_by  text not null default '',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);
create index if not exists idx_documents_owner on documents(owner_type, owner_id);
create index if not exists idx_documents_category on documents(category);
create trigger trg_documents_updated before update on documents
  for each row execute function set_updated_at();

alter table documents enable row level security;
