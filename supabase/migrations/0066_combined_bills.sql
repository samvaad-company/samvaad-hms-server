-- Combined bills: every statement made from the Billing screen is kept, with its own invoice number, so it can be traced later.
-- `snapshot` is the statement exactly as it was issued (lines, prescriptions, totals); the other columns make the history searchable.
-- (MongoDB needs none of this.)
create table if not exists combined_bills (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  invoice_no    text not null,
  patient_id    bigint not null references patients(id),
  patient_name  text not null default '',
  period_from   date,
  period_to     date,
  bill_count    integer not null default 0,
  gross         numeric(12,2) not null default 0,
  discount      numeric(12,2) not null default 0,
  gst           numeric(12,2) not null default 0,
  total         numeric(12,2) not null default 0,
  paid          numeric(12,2) not null default 0,
  due           numeric(12,2) not null default 0,
  snapshot      jsonb not null,
  created_by    text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (hospital_id, invoice_no)
);
create index if not exists idx_combined_bills_patient on combined_bills(hospital_id, patient_id);

drop trigger if exists trg_combined_bills_updated on combined_bills;
create trigger trg_combined_bills_updated before update on combined_bills for each row execute function set_updated_at();
