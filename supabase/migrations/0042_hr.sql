-- HR: staff profile fields, leave (types + requests), shifts and the duty roster, salary structures, monthly payroll runs
-- and payslips. (MongoDB needs none of this.)

alter table staff
  add column if not exists employee_no     text,
  add column if not exists gender          text not null default '',
  add column if not exists dob             text,
  add column if not exists address         text not null default '',
  add column if not exists qualification   text not null default '',
  add column if not exists licence_no      text not null default '',
  add column if not exists licence_expiry  text,
  add column if not exists emergency_name  text not null default '',
  add column if not exists emergency_phone text not null default '';
create unique index if not exists uq_staff_employee_no on staff(hospital_id, employee_no) where employee_no is not null;

create table if not exists hr_leave_types (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  name          text not null,
  code          text not null,
  days_per_year integer not null default 0 check (days_per_year >= 0),
  paid          boolean not null default true,
  active        boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (hospital_id, name),
  unique (hospital_id, code)
);

create table if not exists hr_leave_requests (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  staff_id      bigint not null references staff(id) on delete cascade,
  staff_name    text not null,
  department    text not null default '',
  leave_type_id bigint not null references hr_leave_types(id),
  type_name     text not null,
  type_code     text not null,
  paid          boolean not null default true,
  from_date     text not null,
  to_date       text not null,
  days          integer not null check (days >= 1),
  reason        text not null default '',
  status        text not null default 'Pending' check (status in ('Pending','Approved','Rejected','Cancelled')),
  applied_by    text not null default '',
  applied_at    timestamptz not null default now(),
  decided_by    text,
  decided_at    timestamptz,
  decision_note text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  check (to_date >= from_date)
);
create index if not exists idx_hr_leave_staff on hr_leave_requests(hospital_id, staff_id, status);
create index if not exists idx_hr_leave_dates on hr_leave_requests(hospital_id, from_date, to_date);

create table if not exists hr_shifts (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  name        text not null,
  code        text not null,
  start       text not null check (start ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  "end"       text not null check ("end" ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (hospital_id, name),
  unique (hospital_id, code)
);

create table if not exists hr_roster (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  staff_id    bigint not null references staff(id) on delete cascade,
  work_date   text not null,
  shift_id    bigint not null references hr_shifts(id),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  -- A person works at most one shift a day, whatever the application does.
  unique (staff_id, work_date)
);
create index if not exists idx_hr_roster_date on hr_roster(hospital_id, work_date);

create table if not exists hr_salaries (
  id              bigint generated by default as identity primary key,
  hospital_id     integer not null references hospitals(id),
  staff_id        bigint not null references staff(id) on delete cascade,
  basic           numeric(12,2) not null check (basic >= 0),
  hra             numeric(12,2) not null default 0 check (hra >= 0),
  allowances      numeric(12,2) not null default 0 check (allowances >= 0),
  pf_percent      numeric(5,2) not null default 12 check (pf_percent between 0 and 100),
  prof_tax        numeric(12,2) not null default 0 check (prof_tax >= 0),
  other_deduction numeric(12,2) not null default 0 check (other_deduction >= 0),
  updated_by      text not null default '',
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (staff_id)
);

create table if not exists hr_payroll_runs (
  id           bigint generated by default as identity primary key,
  hospital_id  integer not null references hospitals(id),
  month        text not null check (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  status       text not null default 'Draft' check (status in ('Draft','Finalized')),
  staff_count  integer not null default 0,
  total_gross  numeric(14,2) not null default 0,
  total_net    numeric(14,2) not null default 0,
  created_by   text not null default '',
  finalized_by text,
  finalized_at timestamptz,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  -- One payroll run per month.
  unique (hospital_id, month)
);

create table if not exists hr_payslips (
  id                bigint generated by default as identity primary key,
  hospital_id       integer not null references hospitals(id),
  run_id            bigint not null references hr_payroll_runs(id) on delete cascade,
  staff_id          bigint not null references staff(id) on delete cascade,
  staff_name        text not null,
  employee_no       text not null default '',
  role              text not null default '',
  department        text not null default '',
  month             text not null,
  month_days        integer not null,
  paid_days         integer not null,
  unpaid_leave_days integer not null default 0,
  lop_adjust        integer not null default 0,
  absent_days       integer not null default 0,
  basic             numeric(12,2) not null default 0,
  hra               numeric(12,2) not null default 0,
  allowances        numeric(12,2) not null default 0,
  gross             numeric(12,2) not null default 0,
  pf                numeric(12,2) not null default 0,
  prof_tax          numeric(12,2) not null default 0,
  other_deduction   numeric(12,2) not null default 0,
  net_pay           numeric(12,2) not null default 0,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  unique (run_id, staff_id)
);
