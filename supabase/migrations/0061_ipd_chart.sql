-- Inpatient chart: the day's treatment sheet (plan, instructions, investigations, when to call the doctor, doctor's sign-off),
-- intake and output charting, and a few details of the stay (allergy check, payer, planned discharge date).
create table if not exists ipd_sheets (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  admission_id  bigint not null references ipd_admissions(id) on delete cascade,
  sheet_date    date not null,
  plan          text not null default '',
  instructions  text not null default '[]',
  investigations text not null default '[]',
  call_doctor   text not null default '{}',
  signed_by     text,
  signed_at     timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (admission_id, sheet_date)
);

create table if not exists ipd_io (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  admission_id  bigint not null references ipd_admissions(id) on delete cascade,
  kind          text not null check (kind in ('In','Out')),
  category      text not null default '',
  amount_ml     integer not null default 0,
  recorded_at   timestamptz not null default now(),
  note          text not null default '',
  recorded_by   text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_ipd_io_admission on ipd_io(admission_id, recorded_at desc);

alter table ipd_admissions add column if not exists allergy_status text not null default '';
alter table ipd_admissions add column if not exists allergies text not null default '';
alter table ipd_admissions add column if not exists payer text not null default 'Self pay';
alter table ipd_admissions add column if not exists planned_discharge_date date;
alter table ipd_admissions add column if not exists discharge_stage text not null default '';

do $$
declare t text;
begin
  foreach t in array array['ipd_sheets','ipd_io']
  loop
    execute format('drop trigger if exists trg_%1$s_updated on %1$s', t);
    execute format('create trigger trg_%1$s_updated before update on %1$s for each row execute function set_updated_at()', t);
  end loop;
end $$;
