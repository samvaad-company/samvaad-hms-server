-- ============================================================================
-- Samvaad HMS: awareness programmes posted by hospitals and shown in the patient portal.
--   * awareness_events: a health camp, webinar, vaccination drive etc. Draft -> Published -> Cancelled.
--     audience 'all' reaches every patient on the portal; 'hospital' only the posting hospital's patients.
--   * awareness_reads: that a patient has opened a programme, so the portal can show what is new.
-- ============================================================================

create table if not exists awareness_events (
  id             bigint generated by default as identity primary key,
  hospital_id    bigint not null references hospitals(id) on delete cascade,
  hospital_name  text not null default '',
  title          text not null,
  category       text not null default 'Other',
  summary        text not null default '',
  details        text not null default '',
  event_date     text not null default '',
  event_time     text not null default '',
  end_date       text not null default '',
  mode           text not null default 'In person' check (mode in ('In person', 'Online')),
  venue          text not null default '',
  link           text not null default '',
  contact        text not null default '',
  audience       text not null default 'all' check (audience in ('all', 'hospital')),
  image          text not null default '',
  status         text not null default 'Draft' check (status in ('Draft', 'Published', 'Cancelled')),
  published_at   timestamptz,
  cancelled_at   timestamptz,
  created_by     text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists idx_awareness_events_hospital on awareness_events(hospital_id, status);
create index if not exists idx_awareness_events_published on awareness_events(status, published_at desc);

create table if not exists awareness_reads (
  id           bigint generated by default as identity primary key,
  hospital_id  bigint not null references hospitals(id) on delete cascade,
  patient_id   bigint not null references patients(id) on delete cascade,
  event_id     bigint not null references awareness_events(id) on delete cascade,
  read_at      timestamptz not null default now(),
  unique (patient_id, event_id)
);
create index if not exists idx_awareness_reads_event on awareness_reads(event_id);

alter table awareness_events enable row level security;
alter table awareness_reads enable row level security;
