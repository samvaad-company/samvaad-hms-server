-- OPD vitals log: a patient's vitals can be taken any number of times in a day, each reading kept with its time and who took it.
-- opd_visits keeps the latest reading for the queue; this table is the full history.
create table if not exists opd_vitals (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  visit_id      bigint not null references opd_visits(id) on delete cascade,
  patient_id    bigint,
  recorded_at   timestamptz not null default now(),
  bp_systolic   integer,
  bp_diastolic  integer,
  pulse         integer,
  temperature   numeric(4,1),
  spo2          integer,
  note          text not null default '',
  recorded_by   text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_opd_vitals_visit on opd_vitals(visit_id, recorded_at desc);
create index if not exists idx_opd_vitals_patient on opd_vitals(hospital_id, patient_id, recorded_at desc);

drop trigger if exists trg_opd_vitals_updated on opd_vitals;
create trigger trg_opd_vitals_updated before update on opd_vitals for each row execute function set_updated_at();
