-- ============================================================================
-- Samvaad HMS: AI token usage, monthly limits and extra grants.
--   * chat_messages gains the tokens each AI answer used.
--   * ai_token_usage is the ledger (one line per answer); it outlives chat threads.
--   * ai_token_limits: monthly limit, hospital default (user_id null) or per person; a person can also be
--     paused (blocked) by an admin, which stops their AI use until resumed.
--   * ai_token_grants: extra tokens an admin gives one person for one month.
-- ============================================================================

alter table chat_messages
  add column if not exists tokens_in    integer,
  add column if not exists tokens_out   integer,
  add column if not exists tokens_total integer;

create table if not exists ai_token_usage (
  id             bigint generated by default as identity primary key,
  hospital_id    bigint references hospitals(id) on delete cascade,
  user_id        bigint not null references users(id) on delete cascade,
  user_name      text not null default '',
  role           text not null default '',
  thread_id      bigint,
  message_id     bigint,
  prompt_tokens  integer not null default 0,
  output_tokens  integer not null default 0,
  total_tokens   integer not null default 0,
  month          text not null,
  created_at     timestamptz not null default now()
);
create index if not exists idx_ai_usage_hospital_month on ai_token_usage(hospital_id, month);
create index if not exists idx_ai_usage_user_month on ai_token_usage(user_id, month);

create table if not exists ai_token_limits (
  id             bigint generated by default as identity primary key,
  hospital_id    bigint references hospitals(id) on delete cascade,
  user_id        bigint references users(id) on delete cascade,
  monthly_limit  integer check (monthly_limit >= 0),  -- null = follows the hospital default
  blocked        boolean not null default false,
  updated_by     text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create unique index if not exists uq_ai_limits_user on ai_token_limits(hospital_id, user_id) where user_id is not null;
create unique index if not exists uq_ai_limits_default on ai_token_limits(hospital_id) where user_id is null;
create trigger trg_ai_token_limits_updated before update on ai_token_limits
  for each row execute function set_updated_at();

create table if not exists ai_token_grants (
  id           bigint generated by default as identity primary key,
  hospital_id  bigint references hospitals(id) on delete cascade,
  user_id      bigint not null references users(id) on delete cascade,
  month        text not null,
  tokens       integer not null check (tokens > 0),
  note         text not null default '',
  granted_by   text not null default '',
  created_at   timestamptz not null default now()
);
create index if not exists idx_ai_grants_user_month on ai_token_grants(user_id, month);

alter table ai_token_usage  enable row level security;
alter table ai_token_limits enable row level security;
alter table ai_token_grants enable row level security;
