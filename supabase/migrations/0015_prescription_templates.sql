-- ============================================================================
-- Samvaad HMS — Prescription quick templates
-- Doctors can save a set of medicines as a reusable template from the
-- prescription builder, and later edit or delete it. Private per doctor.
-- ============================================================================

create table if not exists prescription_templates (
  id         bigint generated by default as identity primary key,
  doctor_id  bigint not null references doctors(id) on delete cascade,
  name       text not null default '',
  items      jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_prescription_templates_doctor
  on prescription_templates(doctor_id);
create trigger trg_prescription_templates_updated before update on prescription_templates
  for each row execute function set_updated_at();

alter table prescription_templates enable row level security;
