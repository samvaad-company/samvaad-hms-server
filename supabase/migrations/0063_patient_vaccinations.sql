-- A patient's vaccinations, entered by staff. The date is never assumed: it is either given, or marked "exact date not known"
-- (optionally with an approximate time such as "2021" or "March 2021").
create table if not exists patient_vaccinations (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  patient_id    bigint not null references patients(id) on delete cascade,
  vaccine       text not null,
  dose          text not null default '',
  given_on      date,
  date_unknown  boolean not null default false,
  approx_when   text not null default '',
  next_due      date,
  note          text not null default '',
  recorded_by   text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  check (date_unknown or given_on is not null)
);
create index if not exists idx_patient_vaccinations_patient on patient_vaccinations(hospital_id, patient_id);

drop trigger if exists trg_patient_vaccinations_updated on patient_vaccinations;
create trigger trg_patient_vaccinations_updated before update on patient_vaccinations for each row execute function set_updated_at();
