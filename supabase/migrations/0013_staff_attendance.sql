-- ============================================================================
-- Samvaad HMS — Staff attendance
-- The Attendance tab showed illustrative rows with no way to record anything.
-- One row per staff member per day: punch in creates it, punch out closes it.
-- ============================================================================

create table if not exists staff_attendance (
  id         bigint generated by default as identity primary key,
  staff_id   bigint not null references staff(id) on delete cascade,
  staff_name text not null default '',
  work_date  text not null default '',
  punch_in   text not null default '',
  punch_out  text not null default '',
  minutes    integer not null default 0 check (minutes >= 0),
  status     text not null default 'Present',
  note       text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists uniq_attendance_staff_day
  on staff_attendance(staff_id, work_date);
create trigger trg_staff_attendance_updated before update on staff_attendance
  for each row execute function set_updated_at();

alter table staff_attendance enable row level security;
