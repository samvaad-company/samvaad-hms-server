-- ── tasks ─────────────────────────────────────────────────────────────────────
create table if not exists tasks (
  id            bigint generated by default as identity primary key,
  title         text not null,
  description   text not null default '',
  goal          text not null default '',
  assignee_id   bigint references staff(id) on delete set null,
  assignee_name text not null default 'Unassigned',
  assigned_by   text not null default '',
  priority      text not null default 'Medium' check (priority in ('Low','Medium','High','Urgent')),
  status        text not null default 'To Do' check (status in ('To Do','In Progress','Blocked','Done')),
  due_date      text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_tasks_status on tasks(status);
create index if not exists idx_tasks_assignee on tasks(assignee_id);
create trigger trg_tasks_updated before update on tasks
  for each row execute function set_updated_at();

-- ── scribe_notes ──────────────────────────────────────────────────────────────
create table if not exists scribe_notes (
  id             bigint generated by default as identity primary key,
  appointment_id bigint references appointments(id) on delete set null,
  patient_id     bigint references patients(id) on delete set null,
  patient_name   text not null default '',
  doctor_id      bigint references doctors(id) on delete set null,
  doctor_name    text not null default '',
  transcript     text not null default '',
  brief          text not null default '',
  language       text not null default 'en-IN',
  duration_sec   integer not null default 0 check (duration_sec >= 0),
  status         text not null default 'Saved' check (status in ('Draft','Saved','Signed')),
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create index if not exists idx_scribe_appointment on scribe_notes(appointment_id);
create index if not exists idx_scribe_patient on scribe_notes(patient_id);
create trigger trg_scribe_notes_updated before update on scribe_notes
  for each row execute function set_updated_at();

-- ── Row Level Security (service-role only, matching the rest of the schema) ────
alter table tasks        enable row level security;
alter table scribe_notes enable row level security;
