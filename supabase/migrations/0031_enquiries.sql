-- Enquiries: leads captured before registration (follow up, convert to a patient, or close).
-- (MongoDB needs none of this — it's schemaless.)
create table if not exists enquiries (
  id bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  name text not null,
  mobile text not null default '',
  department text not null default '',
  interested_in text not null default '',
  source text not null default '',
  estimated_value numeric(14,2) not null default 0,
  follow_up_on text,   -- yyyy-mm-dd, like the other date columns
  notes text not null default '',
  status text not null default 'Open' check (status in ('Open','Follow-up','Converted','Closed')),
  contacts integer not null default 1,
  converted_patient_id bigint references patients(id) on delete set null,
  history jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists idx_enquiries_hospital_status on enquiries(hospital_id, status);
create index if not exists idx_enquiries_follow_up on enquiries(hospital_id, follow_up_on);
create trigger trg_enquiries_updated before update on enquiries
  for each row execute function set_updated_at();
