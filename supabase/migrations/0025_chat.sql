-- ============================================================================
-- Samvaad HMS — AI Chat
-- Per-user chat threads with an AI assistant. A thread belongs to exactly one
-- user (their own private chat history) — hospital_id/radiology_center_id/
-- lab_center_id are stored for tenant hygiene/auditing only, not visibility;
-- visibility is enforced purely by user_id ownership at the application layer.
-- ============================================================================

create table if not exists chat_threads (
  id                   bigint generated by default as identity primary key,
  hospital_id          bigint references hospitals(id) on delete cascade,
  radiology_center_id  bigint references radiology_centers(id) on delete cascade,
  lab_center_id        bigint references lab_centers(id) on delete cascade,
  user_id              bigint not null references users(id) on delete cascade,
  title                text not null default 'New chat',
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);
create index if not exists idx_chat_threads_user on chat_threads(user_id);
create index if not exists idx_chat_threads_updated on chat_threads(updated_at);
create trigger trg_chat_threads_updated before update on chat_threads
  for each row execute function set_updated_at();

create table if not exists chat_messages (
  id          bigint generated by default as identity primary key,
  thread_id   bigint not null references chat_threads(id) on delete cascade,
  role        text not null check (role in ('user','assistant')),
  content     text not null default '',
  sources     text[],
  created_at  timestamptz not null default now()
);
create index if not exists idx_chat_messages_thread on chat_messages(thread_id);
create index if not exists idx_chat_messages_created on chat_messages(created_at);

alter table chat_threads  enable row level security;
alter table chat_messages enable row level security;
