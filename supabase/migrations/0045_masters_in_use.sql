-- Setup masters put to work: a patient's category, income group and visit purpose, an appointment's visit purpose, and invoices
-- raised from the service catalogue (a payment mode on the bill and its line items). (MongoDB needs none of this.)

alter table patients
  add column if not exists patient_category text,
  add column if not exists income_group     text,
  add column if not exists visit_purpose    text;

alter table appointments add column if not exists visit_purpose text;

alter table bills add column if not exists payment_mode text;

create table if not exists bill_items (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  bill_id     bigint not null references bills(id) on delete cascade,
  service_id  bigint,
  code        text not null default '',
  name        text not null,
  quantity    integer not null default 1 check (quantity >= 1),
  unit_price  numeric(12,2) not null default 0 check (unit_price >= 0),
  gst_rate    numeric(5,2) not null default 0 check (gst_rate between 0 and 100),
  hsn_sac     text not null default '',
  amount      numeric(12,2) not null default 0 check (amount >= 0),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists idx_bill_items_bill on bill_items(bill_id);
