-- CSSD (central sterile services): sterilizers, instrument sets and their sterility, sterilization cycles, requests /
-- issues / returns of sets, and a hospital's own shelf-life settings. (MongoDB needs none of this.)

create table if not exists cssd_sterilizers (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id),
  name        text not null,
  method      text not null check (method in ('Autoclave (vacuum)','Autoclave (gravity)','Ethylene oxide','Dry heat','Plasma (H2O2)')),
  location    text not null default '',
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (hospital_id, name)
);

create table if not exists cssd_sets (
  id              bigint generated by default as identity primary key,
  hospital_id     integer not null references hospitals(id),
  set_no          text not null,
  name            text not null,
  type            text not null default 'Surgical',
  department_id   bigint references departments(id) on delete set null,
  department_name text not null default '',
  instruments     jsonb not null default '[]'::jsonb,
  usage_charge    numeric(12,2) not null default 0,
  status          text not null default 'Dirty' check (status in ('Dirty','Packed','In cycle','Sterile','Issued')),
  packaging       text check (packaging in ('Pouched','Wrapped','Rigid container')),
  sterile_until   text,
  last_cycle_id   bigint,
  times_processed integer not null default 0,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (hospital_id, set_no)
);
create index if not exists idx_cssd_sets_status on cssd_sets(hospital_id, status);

create table if not exists cssd_cycles (
  id              bigint generated by default as identity primary key,
  hospital_id     integer not null references hospitals(id),
  cycle_no        text not null,
  sterilizer_id   bigint not null references cssd_sterilizers(id),
  sterilizer_name text not null,
  method          text not null,
  started_at      timestamptz not null default now(),
  started_by      text not null default '',
  set_ids         jsonb not null default '[]'::jsonb,
  temp_c          numeric(6,1) not null,
  pressure_psi    numeric(6,1) not null,
  exposure_min    integer not null,
  indicator       text not null default 'pending' check (indicator in ('pending','pass','fail')),
  status          text not null default 'Running' check (status in ('Running','Passed','Failed','Quarantined')),
  result_by       text,
  result_at       timestamptz,
  note            text not null default '',
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  unique (hospital_id, cycle_no)
);
-- A chamber runs one cycle at a time, whatever the application does.
create unique index if not exists uq_cssd_cycle_running on cssd_cycles(sterilizer_id) where status = 'Running';

create table if not exists cssd_issues (
  id              bigint generated by default as identity primary key,
  hospital_id     integer not null references hospitals(id),
  issue_no        text,
  set_id          bigint not null references cssd_sets(id),
  set_no          text not null,
  set_name        text not null,
  patient_id      bigint references patients(id) on delete set null,
  patient_name    text not null default '',
  department_name text not null default '',
  case_id         bigint,
  case_label      text not null default '',
  status          text not null default 'Requested' check (status in ('Requested','Issued','Returned','Cancelled')),
  requested_at    timestamptz not null default now(),
  requested_by    text not null default '',
  issued_at       timestamptz,
  issued_by       text,
  expected_back   timestamptz,
  returned_at     timestamptz,
  returned_by     text,
  investigate     boolean not null default false,
  return_note     text not null default '',
  charge          numeric(12,2) not null default 0,
  bill_number     text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create unique index if not exists uq_cssd_issue_no on cssd_issues(hospital_id, issue_no) where issue_no is not null;
-- A set has at most one live request or issue at a time.
create unique index if not exists uq_cssd_issue_live_set on cssd_issues(set_id) where status in ('Requested','Issued');

create table if not exists cssd_settings (
  id          bigint generated by default as identity primary key,
  hospital_id integer not null references hospitals(id) unique,
  shelf_life  jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['cssd_sterilizers','cssd_sets','cssd_cycles','cssd_issues','cssd_settings']
  loop
    execute format('drop trigger if exists trg_%1$s_updated on %1$s', t);
    execute format('create trigger trg_%1$s_updated before update on %1$s for each row execute function set_updated_at()', t);
  end loop;
end $$;
