-- Follow-ups: planned return visits, marked Done or Missed by the doctor or the front desk.
-- (MongoDB needs none of this — it's schemaless.)
create table if not exists followups (
  id               bigint generated by default as identity primary key,
  hospital_id      integer not null references hospitals(id),
  patient_id       bigint references patients(id) on delete set null,
  patient_name     text not null,
  patient_code     text not null default '',
  doctor_id        bigint references doctors(id) on delete set null,
  doctor           text not null default '',
  reason           text not null,
  due_on           text not null,        -- yyyy-mm-dd, like the other date columns
  status           text not null default 'Pending' check (status in ('Pending','Done','Missed')),
  created_by       text not null default '',
  created_by_role  text not null default '',
  resolved_by      text,
  resolved_by_role text,
  resolved_on      text,
  reschedules      integer not null default 0,
  note             text not null default '',
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists idx_followups_hospital_status on followups(hospital_id, status, due_on);
create index if not exists idx_followups_doctor on followups(doctor_id);
create trigger trg_followups_updated before update on followups
  for each row execute function set_updated_at();
