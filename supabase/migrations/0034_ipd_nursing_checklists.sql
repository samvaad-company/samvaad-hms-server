-- IPD: fuller admissions (type, MLC, family contact, deposit, primary nurse, diet), bed rates,
-- the nurse station (vitals, IV lines, dose log, ward tasks, handover, alert acknowledgements)
-- and checklists. (MongoDB needs none of this — it's schemaless.)

alter table wards add column if not exists daily_rate numeric(12,2) not null default 0;

alter table ipd_admissions
  add column if not exists admission_no        text not null default '',
  add column if not exists admission_type      text not null default 'Planned',
  add column if not exists is_mlc              boolean not null default false,
  add column if not exists family_name         text not null default '',
  add column if not exists family_relation     text not null default '',
  add column if not exists family_phone        text not null default '',
  add column if not exists deposit_amount      numeric(12,2) not null default 0,
  add column if not exists deposit_mode        text not null default '',
  add column if not exists primary_nurse_id    bigint references staff(id) on delete set null,
  add column if not exists primary_nurse       text not null default '',
  add column if not exists expected_stay_days  integer,
  add column if not exists diet                text not null default '';
alter table ipd_admissions drop constraint if exists ipd_admissions_type_check;
alter table ipd_admissions add constraint ipd_admissions_type_check
  check (admission_type in ('Emergency','Planned','Day care','Maternity','Transfer in'));

create table if not exists ipd_vitals (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  admission_id  bigint not null references ipd_admissions(id) on delete cascade,
  recorded_at   timestamptz not null default now(),
  temp_c        numeric(4,1),
  pulse         integer,
  bp_systolic   integer,
  bp_diastolic  integer,
  spo2          integer,
  resp_rate     integer,
  note          text not null default '',
  recorded_by   text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_ipd_vitals_admission on ipd_vitals(admission_id, recorded_at desc);

create table if not exists ipd_iv_lines (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  admission_id  bigint not null references ipd_admissions(id) on delete cascade,
  fluid         text not null,
  volume_ml     integer not null,
  rate_ml_hr    integer not null,
  started_at    timestamptz not null default now(),
  stopped_at    timestamptz,
  status        text not null default 'Running' check (status in ('Running','Stopped','Completed')),
  started_by    text not null default '',
  note          text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_ipd_iv_admission on ipd_iv_lines(admission_id, status);

create table if not exists ipd_dose_log (
  id             bigint generated by default as identity primary key,
  hospital_id    integer not null references hospitals(id),
  admission_id   bigint not null references ipd_admissions(id) on delete cascade,
  medication_id  bigint not null references ipd_medications(id) on delete cascade,
  scheduled_at   timestamptz not null,
  status         text not null check (status in ('Given','Held')),
  given_at       timestamptz not null default now(),
  given_by       text not null default '',
  note           text not null default '',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  unique (medication_id, scheduled_at)
);
create index if not exists idx_ipd_dose_admission on ipd_dose_log(admission_id, scheduled_at desc);

create table if not exists ipd_nursing_tasks (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  admission_id  bigint references ipd_admissions(id) on delete cascade,
  title         text not null,
  due_at        timestamptz,
  status        text not null default 'To do' check (status in ('To do','Done')),
  created_by    text not null default '',
  done_by       text,
  done_at       timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_ipd_tasks_hospital on ipd_nursing_tasks(hospital_id, status, due_at);

create table if not exists ipd_handovers (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  admission_id  bigint not null references ipd_admissions(id) on delete cascade,
  shift         text not null check (shift in ('Morning','Evening','Night')),
  shift_date    text not null,
  note          text not null,
  author        text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists idx_ipd_handover_admission on ipd_handovers(admission_id, shift_date);

create table if not exists ipd_alert_acks (
  id           bigint generated by default as identity primary key,
  hospital_id  integer not null references hospitals(id),
  alert_key    text not null,
  action       text not null check (action in ('Acknowledged','Dismissed')),
  by           text not null default '',
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (hospital_id, alert_key)
);

create table if not exists ipd_checklist_templates (
  id           bigint generated by default as identity primary key,
  hospital_id  integer not null references hospitals(id),
  name         text not null,
  scope        text not null default 'Inpatient (IPD)',
  description  text not null default '',
  items        jsonb not null default '[]'::jsonb,
  active       boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists ipd_checklists (
  id              bigint generated by default as identity primary key,
  hospital_id     integer not null references hospitals(id),
  template_id     bigint references ipd_checklist_templates(id) on delete set null,
  name            text not null,
  scope           text not null default 'Inpatient (IPD)',
  admission_id    bigint references ipd_admissions(id) on delete set null,
  patient_id      bigint references patients(id) on delete set null,
  patient_name    text not null,
  patient_code    text not null default '',
  items           jsonb not null default '[]'::jsonb,
  ticks           jsonb not null default '{}'::jsonb,
  status          text not null default 'In progress' check (status in ('In progress','Complete','Cancelled')),
  started_by      text not null default '',
  completed_by    text,
  completed_at    timestamptz,
  cancelled_reason text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists idx_ipd_checklists_hospital on ipd_checklists(hospital_id, status);

do $$
declare t text;
begin
  foreach t in array array['ipd_vitals','ipd_iv_lines','ipd_dose_log','ipd_nursing_tasks','ipd_handovers','ipd_alert_acks','ipd_checklist_templates','ipd_checklists']
  loop
    execute format('drop trigger if exists trg_%1$s_updated on %1$s', t);
    execute format('create trigger trg_%1$s_updated before update on %1$s for each row execute function set_updated_at()', t);
  end loop;
end $$;
