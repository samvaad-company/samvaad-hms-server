-- IPD: an admission needs a signed admission consent (the consent it used is remembered, so one consent covers one admission),
-- and a discharge needs every department the patient used in-house to clear the patient first.
-- (MongoDB needs none of this.)
alter table ipd_admissions add column if not exists admission_consent_id bigint;

create table if not exists ipd_discharge_clearances (
  id            bigint generated by default as identity primary key,
  hospital_id   integer not null references hospitals(id),
  admission_id  bigint not null references ipd_admissions(id) on delete cascade,
  department    text not null,
  status        text not null default 'Pending' check (status in ('Pending','Cleared','Flagged')),
  amount_due    numeric(12,2) not null default 0,
  note          text not null default '',
  round         integer not null default 1,
  requested_by  text not null default '',
  requested_at  timestamptz not null default now(),
  responded_by  text not null default '',
  responded_at  timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  unique (admission_id, department)
);
create index if not exists idx_ipd_clearances_admission on ipd_discharge_clearances(hospital_id, admission_id);
create index if not exists idx_ipd_clearances_open on ipd_discharge_clearances(hospital_id, status);

drop trigger if exists trg_ipd_clearances_updated on ipd_discharge_clearances;
create trigger trg_ipd_clearances_updated before update on ipd_discharge_clearances for each row execute function set_updated_at();
